/**
 * dsh-telegram — the Telegram session core and the single engine import point
 * (DESIGN.md 3.3).
 *
 * Everything that knows GramJS lives here. `auth.js` receives a client instance
 * from this module, `store.js` never touches the engine, and the operation
 * modules (`chats.js`, `messages.js`, `search.js`) only see `host`.
 *
 * Engine facts verified against the pinned dependency `telegram@2.26.22` before
 * writing this file (tarball downloaded into /tmp and read there; the plugin
 * directory carries no node_modules of its own at this stage — installing them
 * is the verifier's step, DESIGN 1.7 / captain's t3 note):
 * - top-level runtime exports (`index.js`): `Api`, `TelegramClient`,
 *   `Connection`, `version`, `Logger`, `utils`, `errors`, `sessions`,
 *   `extensions`, `helpers`, `client`, `password`, `tl`;
 * - `new TelegramClient(session, apiId, apiHash, clientParams)`
 *   (`client/TelegramClient.d.ts:41`);
 * - **a raw string session is a trap**: `client/telegramBaseClient.js:70-74`
 *   converts a string into a `StoreSession`, and `sessions/StoreSession.js`
 *   writes a `./<name>` localStorage directory **in the current working
 *   directory** (and rejects the name `"session"`). That would put the secret in
 *   the plugin directory, which DESIGN 3.5 forbids, so this module always passes
 *   a `new sessions.StringSession(value)` instance — `StringSession.save()` only
 *   returns a string and never touches the disk (`sessions/StringSession.js`);
 * - `TelegramClientParams` (`client/telegramBaseClient.d.ts:19-127`):
 *   `connectionRetries` (default 5), `requestRetries` (5), `autoReconnect`
 *   (true), `reconnectRetries` (**default Infinity**), `retryDelay` (1000 ms),
 *   `deviceModel`, `systemVersion`, `appVersion`, `langCode`, `baseLogger`;
 * - `connect(): Promise<boolean>` (`TelegramClient.d.ts:1014`), `get connected()`,
 *   `get disconnected()`, `disconnect()`, `destroy()`
 *   (`telegramBaseClient.d.ts:199-207`), `setLogLevel()` (`:340`); `destroy()`
 *   sets `_destroyed`, which is what ends the engine's own ping loop
 *   (`client/updates.js:164-169 while (!client._destroyed)`), so disposal uses
 *   `destroy()` and not merely `disconnect()`;
 * - `checkAuthorization()` (`TelegramClient.d.ts:92`, `client/auth.js:55-62` —
 *   an `updates.GetState` probe that returns false on any failure),
 *   `getMe()`, `getEntity()`, `getInputEntity()` (`:993`),
 *   `getPeerId(peer, addMark)` (`:1007`, `client/users.js` — accepts a decimal
 *   string, adds the `-100` channel mark and negates group ids), `invoke()`
 *   (`:892`);
 * - `Api.auth.LogOut` really exists at runtime: `tl/apiTl.js:1418`
 *   `auth.logOut#3e72ba19 = auth.LoggedOut;` and `tl/api.d.ts:21245`
 *   (`CONSTRUCTOR_ID 1047706137`), generated by `buildApiFromTlSchema` in
 *   `tl/api.js`.
 *
 * Error names are never imported from the engine (captain's t3 note): only
 * `RPCError` plus a short subclass list exist in `telegram/errors`, and any
 * other RPC error arrives as the base `RPCError` whose message starts with the
 * canonical Telegram token. All normalization therefore goes through
 * `toTelegramError` in `./errors.js`.
 *
 * Resource ownership (DESIGN 3.1, 8.2, `practices.md:2`): the client instance is
 * created inside the plugin fiber, this module registers its own `ctx.effect`
 * disposer in addition to the one DESIGN 3.1 shows in `index.js`, every timer
 * this module starts is tracked and cleared, `dispose()` is idempotent, and each
 * connect attempt is single-flight and bounded.
 *
 * Secrets (DESIGN 3.2): no log line, DTO or error message carries a credential
 * value, a phone number or the stored log-in state. Outgoing text is normalized
 * through `fail()`, which scrubs and caps it.
 *
 * @module dsh-telegram/host/telegram/client
 */

